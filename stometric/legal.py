def get(c) -> dict:
    r = c.execute("SELECT value FROM app_settings WHERE key='legal'").fetchone()
    v = {**DEFAULTS, **((r["value"] if r else None) or {})}
    v["ready"] = all(str(v.get(k) or "").strip() for k, _, req in FIELDS if req)
    v["version"] = VERSION
    return v


def save(c, data: dict) -> dict:
    v = {k: str(data.get(k) or "").strip()[:500] for k, _, _ in FIELDS}
    c.execute("INSERT INTO app_settings(key,value) VALUES ('legal',%s) ON CONFLICT (key) DO UPDATE SET value=EXCLUDED.value", (json.dumps(v, ensure_ascii=False),))
    return v


def need_terms(c, user: dict) -> bool:
    lg = get(c)
    return lg["ready"] and user.get("terms_version") != VERSION


def _ogrn(v: dict) -> str:
    """У ИП — ОГРНИП, у юрлица — ОГРН."""
    return "ОГРНИП" if v["org"].lower().startswith(("ип ", "индивидуальный предприниматель")) else "ОГРН"


