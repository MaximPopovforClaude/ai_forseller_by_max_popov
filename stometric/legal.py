DOCS = {"offer": ("Публичная оферта", offer), "privacy": ("Согласие на обработку персональных данных и Политика", privacy)}


def document(c, key: str, preview: bool = False) -> dict:
    v = get(c)
    title, fn = DOCS[key]
    if not v["ready"] and not preview:
        return {"title": title, "ready": False, "version": VERSION, "sections": []}
    filled = {k: (v.get(k) or f"[{t}]") for k, t, _ in FIELDS}
    return {"title": title, "ready": v["ready"], "version": VERSION, "sections": [{"h": h, "p": p} for h, p in fn(filled)]}
